def interactive_mode(kb_id: str, generation_model_arn: str = GENERATION_MODEL_ARN_LIGHT):
    """Interactive REPL for testing queries"""
    print(f"\n{'='*60}")
    print(" Interactive Knowledge Base Testing")
    print('='*60)
    print(INTERACTIVE_HELP)

    while True:
        try:
            user_input = input("Query> ").strip()

            if not user_input:
                continue

            if user_input.lower() == '/quit':
                print("Goodbye!")
                break

            if user_input.lower() == '/help':
                print(INTERACTIVE_HELP)
                continue

            if user_input.startswith('/retrieve-nofilter '):
                query = user_input[19:].strip()
                response = retrieve_chunks(kb_id, query, use_metadata_filter=False)
                print_retrieval_results(response)

            elif user_input.startswith('/retrieve '):
                query = user_input[10:].strip()
                response = retrieve_chunks(kb_id, query, use_metadata_filter=True)
                print_retrieval_results(response)

            elif user_input.startswith('/compare-generation '):
                query = user_input[20:].strip()
                print("⚠️  Note: /compare-generation makes 2 retrieval + 2 generation calls (highest cost)")
                # Generate both responses
                unfiltered_response = retrieve_and_generate(kb_id, query, use_metadata_filter=False, generation_model_arn=generation_model_arn)
                filtered_response = retrieve_and_generate(kb_id, query, use_metadata_filter=True, generation_model_arn=generation_model_arn)
                print("\n--- UNFILTERED Generation ---")
                print_generation_results(unfiltered_response)
                print("\n--- FILTERED Generation ---")
                print_generation_results(filtered_response)

            elif user_input.startswith('/compare '):
                query = user_input[9:].strip()
                print("⚠️  Note: /compare makes 2 retrieval calls (higher cost)")
                unfiltered = retrieve_chunks(kb_id, query, use_metadata_filter=False)
                filtered = retrieve_chunks(kb_id, query, use_metadata_filter=True)
                print_retrieval_results(unfiltered, "UNFILTERED Results")
                print_retrieval_results(filtered, "FILTERED Results")
                print_comparison_summary(unfiltered.get('retrievalResults', []),
                                         filtered.get('retrievalResults', []))

            elif user_input.startswith('/nofilter '):
                query = user_input[10:].strip()
                response = retrieve_and_generate(kb_id, query, use_metadata_filter=False, generation_model_arn=generation_model_arn)
                print_generation_results(response)

            elif user_input.startswith('/cite '):
                query = user_input[6:].strip()
                response = retrieve_and_generate_with_urls(kb_id, query, use_metadata_filter=True, generation_model_arn=generation_model_arn)
                print_generation_with_urls_results(response)

            else:
                # Default: retrieve and generate with filtering
                response = retrieve_and_generate(kb_id, user_input, use_metadata_filter=True, generation_model_arn=generation_model_arn)
                print_generation_results(response)

        except KeyboardInterrupt:
            print("\nGoodbye!")
            break
        except Exception as e:
            print(f"Error: {e}")


def main():
    parser = argparse.ArgumentParser(
        description="Test AWS Bedrock Knowledge Base retrieval and generation"
    )
    parser.add_argument(
        '--query', '-q',
        type=str,
        help='Query to send to the knowledge base'
    )
    parser.add_argument(
        '--kb-type',
        choices=['default-md', 'automation-pdf'],
        default='default-md',
        help='Type of KB to query (default: default-md)'
    )
    parser.add_argument(
        '--kb-id',
        type=str,
        help='Knowledge base ID (overrides --kb-type lookup)'
    )
    parser.add_argument(
        '--retrieve-only',
        action='store_true',
        help='Only retrieve chunks, do not generate response'
    )
    parser.add_argument(
        '--no-filter',
        action='store_true',
        help='Disable metadata filtering'
    )
    parser.add_argument(
        '--compare',
        action='store_true',
        help='Compare filtered vs unfiltered retrieval'
    )
    parser.add_argument(
        '--num-results', '-n',
        type=int,
        default=5,
        help='Number of chunks to retrieve (default: 5)'
    )
    parser.add_argument(
        '--cite-urls',
        action='store_true',
        help='Use custom generation that injects URLs from metadata into the prompt'
    )
    parser.add_argument(
        '--interactive', '-i',
        action='store_true',
        help='Run in interactive mode'
    )
    parser.add_argument(
        '--model',
        choices=['normal', 'light'],
        default='light',
        help=f'Select which generation model to use (default: light). normal = {GENERATION_MODEL_ARN}, light = {GENERATION_MODEL_ARN_LIGHT}'
    )

    args = parser.parse_args()

    # Resolve generation model ARN
    if args.model == 'normal':
        generation_model_arn = GENERATION_MODEL_ARN
    else:
        generation_model_arn = GENERATION_MODEL_ARN_LIGHT

    # Get KB ID
    if args.kb_id:
        kb_id = args.kb_id
    else:
        kb_name = KB_CONFIGS[args.kb_type]['name']
        print(f"Looking up Knowledge Base: {kb_name}")
        kb_id = get_knowledge_base_id(kb_name)
        if not kb_id:
            print(f"Error: Knowledge Base '{kb_name}' not found")
            return 1

    print(f"Using Knowledge Base ID: {kb_id}")
    print(f"Using generation model: {args.model} ({generation_model_arn})")

    # Interactive mode
    if args.interactive:
        interactive_mode(kb_id, generation_model_arn=generation_model_arn)
        return 0

    # Single query mode
    if not args.query:
        print("Error: --query is required (or use --interactive)")
        return 1

    use_filter = not args.no_filter

    try:
        if args.compare:
            # --compare always runs both filtered and unfiltered (ignores --no-filter)
            unfiltered = retrieve_chunks(kb_id, args.query, use_metadata_filter=False, num_results=args.num_results)
            filtered = retrieve_chunks(kb_id, args.query, use_metadata_filter=True, num_results=args.num_results)
            print_retrieval_results(unfiltered, "UNFILTERED Results")
            print_retrieval_results(filtered, "FILTERED Results")
            print_comparison_summary(unfiltered.get('retrievalResults', []),
                                     filtered.get('retrievalResults', []))
        elif args.retrieve_only:
            response = retrieve_chunks(kb_id, args.query, use_filter, args.num_results)
            print_retrieval_results(response)
        elif args.cite_urls:
            response = retrieve_and_generate_with_urls(
                kb_id, args.query, use_filter, args.num_results
            )
            print_generation_with_urls_results(response)
        else:
            response = retrieve_and_generate(kb_id, args.query, use_filter, args.num_results)
            print_generation_results(response)
    except Exception as e:
        print(f"Error: {e}")
        if args.kb_id:
            print(f"If '--kb-id {kb_id}' is incorrect, try omitting it to look up the KB by name instead.")
        return 1

    return 0


if __name__ == "__main__":
    exit(main())
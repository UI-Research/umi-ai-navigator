def retrieve_chunks(
    kb_id: str,
    query: str,
    use_metadata_filter: bool = True,
    num_results: int = 5,
    manual_filter: Optional[dict] = None
) -> dict:
    """
    Retrieve chunks from the knowledge base.

    Args:
        kb_id: Knowledge Base ID
        query: The query text
        use_metadata_filter: Whether to use LLM-generated metadata filtering
        num_results: Number of results to retrieve
        manual_filter: Optional manual filter to apply (overrides LLM generation)

    Returns:
        Dictionary with retrieval results and metadata
    """
    retrieval_config = build_retrieval_config(num_results, use_metadata_filter, manual_filter)

    filter_status = 'filtered' if (use_metadata_filter and not manual_filter) else (
        'manual_filter' if manual_filter else 'unfiltered'
    )

    try:
        # Retrieve API doc: https://docs.aws.amazon.com/bedrock/latest/APIReference/API_agent-runtime_Retrieve.html
        response = bedrock_agent_runtime.retrieve(
            knowledgeBaseId=kb_id,
            retrievalQuery={'text': query},
            retrievalConfiguration=retrieval_config
        )
        # Botocore responses may not persist arbitrary keys, so wrap in a
        # plain dict that includes the filter status alongside the results.
        return {**response, 'filterStatus': filter_status}
    except bedrock_agent_runtime.exceptions.ValidationException as e:
        # The implicit filter may generate unsupported operators (e.g.
        # STRING_CONTAINS) for certain queries.  Fall back to unfiltered
        # vector search so the question still gets an answer.
        if use_metadata_filter and not manual_filter:
            print(f"Warning: implicit filter failed ({e}), retrying without metadata filter")
            fallback_config = {
                'vectorSearchConfiguration': {
                    'numberOfResults': num_results,
                }
            }
            response = bedrock_agent_runtime.retrieve(
                knowledgeBaseId=kb_id,
                retrievalQuery={'text': query},
                retrievalConfiguration=fallback_config
            )
            return {**response, 'filterStatus': 'fallback_unfiltered'}
        raise
    except Exception as e:
        print(f"Error during retrieval: {e}")
        raise


def retrieve_and_generate(
    kb_id: str,
    query: str,
    use_metadata_filter: bool = True,
    num_results: int = 5,
    manual_filter: Optional[dict] = None,
    generation_model_arn: str = GENERATION_MODEL_ARN_LIGHT
) -> dict:
    """
    Retrieve chunks and generate a response.

    Args:
        kb_id: Knowledge Base ID
        query: The query text
        use_metadata_filter: Whether to use LLM-generated metadata filtering
        num_results: Number of results to retrieve
        manual_filter: Optional manual filter to apply
        generation_model_arn: Model ARN for response generation

    Returns:
        Dictionary with generation results, citations, and retrieved chunks
    """
    retrieval_config = build_retrieval_config(num_results, use_metadata_filter, manual_filter)

    try:
        # Retrieve and Generate API doc: https://docs.aws.amazon.com/bedrock/latest/APIReference/API_agent-runtime_RetrieveAndGenerate.html
        response = bedrock_agent_runtime.retrieve_and_generate(
            input={'text': query},
            retrieveAndGenerateConfiguration={
                'type': 'KNOWLEDGE_BASE',
                'knowledgeBaseConfiguration': {
                    'knowledgeBaseId': kb_id,
                    'modelArn': generation_model_arn,
                    'retrievalConfiguration': retrieval_config
                }
            }
        )
        return response
    except Exception as e:
        print(f"Error during retrieve and generate: {e}")
        raise


def retrieve_and_generate_with_urls(
    kb_id: str,
    query: str,
    use_metadata_filter: bool = True,
    num_results: int = 5,
    url_metadata_key: str = 'url',
    generation_model_arn: str = GENERATION_MODEL_ARN_LIGHT,
    skill: str = None
) -> dict:
    """
    Retrieve chunks, extract URLs from metadata, and generate response with citations.

    This uses a two-step process:
    1. Call retrieve() to get chunks with their metadata (including URLs)
    2. Build a custom prompt with URLs injected, then call the model directly

    This ensures the model sees the URLs and can cite them in its response.

    Args:
        kb_id: Knowledge Base ID
        query: The query text
        use_metadata_filter: Whether to use LLM-generated metadata filtering
        num_results: Number of results to retrieve
        url_metadata_key: The metadata key where URL is stored (default: 'url')
        generation_model_arn: Model ARN for response generation
        skill: Optional skill text (from agentic workflow). Overrides module-level
            SYSTEM_PROMPT when provided. Use this when calling from an orchestrator.

    Returns:
        Dictionary with generated response, sources, and retrieved chunks
    """
    # Step 1: Retrieve chunks (metadata including URL comes back)
    retrieval_response = retrieve_chunks(
        kb_id=kb_id,
        query=query,
        use_metadata_filter=use_metadata_filter,
        num_results=num_results
    )

    results = retrieval_response.get('retrievalResults', [])

    # Fallback: if filtering returned no results, retry without the filter
    if not results and use_metadata_filter:
        print("  No results with filter — retrying without metadata filter")
        retrieval_response = retrieve_chunks(
            kb_id=kb_id,
            query=query,
            use_metadata_filter=False,
            num_results=num_results
        )
        retrieval_response['filterStatus'] = 'fallback_no_results'
        results = retrieval_response.get('retrievalResults', [])

    if not results:
        return {
            'generated_text': "No relevant information found in the knowledge base.",
            'sources': [],
            'retrieval_response': retrieval_response,
            'filter_status': retrieval_response.get('filterStatus', 'unknown')
        }

    # Step 2: Build context string with URLs extracted from metadata
    context_parts = []
    sources = []

    for i, chunk in enumerate(results, 1):
        text = chunk.get('content', {}).get('text', '')
        metadata = chunk.get('metadata', {})

        # Extract URL from metadata (stored during ingestion via .metadata.json)
        url = metadata.get(url_metadata_key, None)

        # Fallback to S3 URI if no custom URL metadata
        if not url:
            s3_location = chunk.get('location', {}).get('s3Location', {})
            url = s3_location.get('uri', 'Unknown source')

        sources.append({
            'index': i,
            'url': url,
            'metadata': {k: v for k, v in metadata.items()
                        if not k.startswith('AMAZON_BEDROCK')},
            'score': chunk.get('score', 'N/A')
        })

        # Build metadata header so the generation model can use tags for
        # prioritization (document_type) and citation (name, source, year).
        meta_lines = [f"[Source {i}]", f"URL: {url}"]
        for key in ('document_name', 'document_type', 'source',
                     'publication_year'):
            value = metadata.get(key)
            if value:
                label = key.replace('_', ' ').title()
                meta_lines.append(f"{label}: {value}")

        context_parts.append("\n".join(meta_lines) + f"\n\n{text}")

    context = "\n\n---\n\n".join(context_parts)

    # Step 3: Build user prompt (context + question only)
    prompt = f"""Sources:
{context}

Question: {query}"""

    # Step 4: Call the model directly via Bedrock Runtime (not the KB agent runtime)
    try:
        # Bedrock Runtime API doc: https://docs.aws.amazon.com/bedrock/latest/APIReference/API_Operations_Amazon_Bedrock_Runtime.html
        bedrock_runtime = boto3.client('bedrock-runtime', region_name=REGION)
        # AWS Anthropic doc: https://docs.aws.amazon.com/bedrock/latest/userguide/model-parameters-anthropic-claude-messages.html
        body_params = {
            'anthropic_version': 'bedrock-2023-05-31',
            'max_tokens': 2048,
            'messages': [{'role': 'user', 'content': prompt}]
        }

        # Agentic workflow: skill overrides the default system prompt
        effective_prompt = skill if skill is not None else SYSTEM_PROMPT
        if effective_prompt:
            body_params['system'] = effective_prompt
        # `invoke_model` doc: https://docs.aws.amazon.com/boto3/latest/reference/services/bedrock-runtime/client/invoke_model.html
        response = bedrock_runtime.invoke_model(
            modelId=generation_model_arn,
            body=json.dumps(body_params)
        )

        result = json.loads(response['body'].read())
        generated_text = result['content'][0]['text']

        return {
            'generated_text': generated_text,
            'sources': sources,
            'retrieval_response': retrieval_response,
            'filter_status': retrieval_response.get('filterStatus', 'unknown')
        }
    except Exception as e:
        print(f"Error during model invocation: {e}")
        raise



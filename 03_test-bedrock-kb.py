# Initialize boto3 clients shared across functions
bedrock_agent_runtime = boto3.client('bedrock-agent-runtime', region_name=REGION)  # KB retrieval & RAG
s3 = boto3.client('s3', region_name=REGION)

GENERATION_MODELS = {
    'normal': GENERATION_MODEL_ARN,
    'light': GENERATION_MODEL_ARN_LIGHT,
}

def load_metadata_schema() -> list:
    """Load metadata schema from S3 for implicit filtering"""
    try:
        # Parse S3 URI
        uri_parts = METADATA_SCHEMA_S3_URI.replace('s3://', '').split('/', 1)
        bucket = uri_parts[0]
        key = uri_parts[1]

        # Download schema
        response = s3.get_object(Bucket=bucket, Key=key)
        schema = json.loads(response['Body'].read().decode('utf-8'))

        return schema
    except Exception as e:
        print(f"Warning: Could not load metadata schema from {METADATA_SCHEMA_S3_URI}: {e}")
        print("Metadata filtering will be disabled.")
        return []


def load_system_prompt(file_path: str = None) -> Optional[str]:
    """Load system prompt from a markdown file.

    Args:
        file_path: Path to the system prompt .md file. If None, uses SYSTEM_PROMPT_PATH.

    Returns:
        The system prompt text, or None if file doesn't exist or can't be read.
    """
    path = file_path or SYSTEM_PROMPT_PATH
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return f.read().strip()
    except FileNotFoundError:
        print(f"Info: System prompt file not found at {path}. Using no system prompt.")
        return None
    except Exception as e:
        print(f"Warning: Could not load system prompt from {path}: {e}")
        return None


# Load schema and system prompt at module initialization so they are accessible by all functions below
METADATA_SCHEMA = load_metadata_schema()
SYSTEM_PROMPT = load_system_prompt()


def build_retrieval_config(
    num_results: int = 5,
    use_metadata_filter: bool = True,
    manual_filter: Optional[dict] = None,
    metadata_schema: list = METADATA_SCHEMA,
    filter_model_id: str = FILTER_GENERATION_MODEL_ARN
) -> dict:
    """Build the shared retrievalConfiguration dict used by retrieve and retrieve_and_generate."""
    vector_search_config = {
        'numberOfResults': num_results,
    }

    if manual_filter:
        vector_search_config['filter'] = manual_filter
    elif use_metadata_filter and metadata_schema:
        vector_search_config['implicitFilterConfiguration'] = {
            'metadataAttributes': metadata_schema,
            'modelArn': filter_model_id
        }

    return {'vectorSearchConfiguration': vector_search_config}


